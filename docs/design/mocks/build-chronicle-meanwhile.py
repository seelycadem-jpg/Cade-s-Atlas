"""Writes chronicle-v1-meanwhile.js for the chronicle mock (chronicle-v1.html).

The Meanwhile section of the Germany chronicle shows what else was happening in the world during one
of its stories. This script copies, from site/data.json (Prototype 1 data), every event that is not one
of the German pilot chain's own events (the ids in atlas-data.js): year, name, place, region, kinds, tier.
The page filters them by the story's years. The tiers are the old data's and stand in for knot, fibre and
strand until every event is rated afresh. Run from the repo root: python3 docs/design/mocks/build-chronicle-meanwhile.py
"""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parents[3]
data = json.loads((root / 'site/data.json').read_text())
own = set(re.findall(r'\{"id":"([^"]+)","y":', (root / 'docs/design/mocks/atlas-data.js').read_text()[:14000]))
rows = []
for e in sorted(data['events'], key=lambda e: (e['y'], e['h'])):
    if e['id'] in own:
        continue
    where = re.sub(r'\s*\([^)]*\)', '', e.get('where') or '').strip()
    rows.append({'y': e['y'], 'h': e['h'], 'w': where, 'r': e['r'], 'c': e.get('c') or [], 'tier': e.get('tier') or 2})
head = ('/* Every event the old atlas data holds outside the German pilot chain: year, name, place, region, kinds and tier,\n'
        '   copied from site/data.json (Prototype 1 data, to be re-rated and rewritten). The chronicle mock filters them by the\n'
        '   years of one story. Generated by build-chronicle-meanwhile.py, not hand-edited. */\n')
(root / 'docs/design/mocks/chronicle-v1-meanwhile.js').write_text(head + 'window.CHRON_MEANWHILE=' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(rows), 'events;', len(own), 'left out')
